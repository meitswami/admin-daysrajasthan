import fs from "fs";

const src = fs.readFileSync(process.env.TEMP + "/864.js", "utf8");
const marker = "JSON.parse('";
const start = src.indexOf(marker);
if (start < 0) {
  console.error("marker not found");
  process.exit(1);
}

let i = start + marker.length;
const chars = [];
while (i < src.length) {
  const ch = src[i];
  if (ch === "\\") {
    const next = src[i + 1];
    if (next === "n") chars.push("\n");
    else if (next === "r") chars.push("\r");
    else if (next === "t") chars.push("\t");
    else if (next === '"' || next === "'" || next === "\\") chars.push(next);
    else if (next === "u") {
      const hex = src.slice(i + 2, i + 6);
      chars.push(String.fromCharCode(parseInt(hex, 16)));
      i += 6;
      continue;
    } else chars.push(next);
    i += 2;
    continue;
  }
  if (ch === "'") break;
  chars.push(ch);
  i++;
}

const decoded = chars.join("");
fs.writeFileSync(process.env.TEMP + "/website-packages-raw.json", decoded);
const packages = JSON.parse(decoded);
console.log("packages", packages.length);

const WEBSITE_THEME_LABEL = {
  romantic: "Romantic & Honeymoon",
  luxury: "Luxury & Heritage",
  desert: "Desert & Adventure",
  wildlife: "Wildlife & Wilderness",
  spiritual: "Spiritual & Mystical",
  heritage: "Luxury & Heritage",
};

const slim = packages.map((p) => {
  const themeIds = [...new Set((p.themes || []).map((t) => (t === "heritage" ? "luxury" : t)))];
  const cities = String(p.cities || "")
    .split("|")
    .map((c) => c.trim())
    .filter(Boolean);
  return {
    slug: p.id,
    tourCode: p.tourCode,
    title: p.title,
    durationDays: p.durationDays,
    duration: p.duration,
    cities,
    citiesRaw: p.cities,
    dayBucket: p.dayBucket,
    themeIds,
    themes: themeIds.map((id) => WEBSITE_THEME_LABEL[id] || id),
    website_url: `https://daysrajasthan.com/packages/${p.id}`,
  };
});

fs.writeFileSync(
  process.env.TEMP + "/website-packages.json",
  JSON.stringify(slim, null, 2)
);
const themeCounts = {};
for (const p of slim) {
  for (const t of p.themeIds || []) themeCounts[t] = (themeCounts[t] || 0) + 1;
}
console.log("theme counts", themeCounts);
